"""JEPA lidar driver for the AIL Cup, Pro class.
GENERATED by ail_cup/make_controller.py from ail_cup/controller_template.py: change the template, not this file.

Every step: the platform's lidar is re-sampled to the 271 beams the model knows (1 degree each, -135..+135,
right -> left, cut at MAX_RANGE, / MAX_RANGE, like core/sensors.clean_lidar), the encoder describes it,
the predictor imagines STEPS steps for every steering option, the probe reads the walls on the whole path,
and the option whose closest wall stays farthest away wins (the same planner as core/planner.py).
Only numpy and the standard library: the weights are packed into WEIGHTS below.
"""
import base64
import io
import math
import zlib

import numpy as np

# __CONSTANTS__

SPEED = 1.8                     # m/s, constant command speed (about what throttle 0.05 gave in AutoDRIVE)
THROTTLE = 0.05                 # the AutoDRIVE throttle the model is told it drives with
AUTODRIVE_MAX_STEER = 0.5236    # rad: steering +-1 of the model = +-30 degrees of the AutoDRIVE car
SMOOTH = 0.01                   # penalty per unit of steering change -> less zig-zag
SAFE_FRONT = 1.0                # m, slow down if something is closer in front (other cars)

WEIGHTS = "__WEIGHTS__"


def relu(x):
    return np.maximum(x, 0)


class Controller:
    def __init__(self, init):
        self.max_steer = init["car"]["max_steer"]
        lidar = init["lidar"]
        model_angles = np.radians(np.arange(-135, 136))                      # the 271 beams the model knows
        beams = np.round((model_angles - lidar["angle_min"]) / lidar["angle_increment"]).astype(int)
        self.beams = np.clip(beams, 0, lidar["n_beams"] - 1)                # outside the fov: the nearest edge beam
        packed = np.load(io.BytesIO(zlib.decompress(base64.b64decode(WEIGHTS))))
        self.w = {key: packed[key].astype(np.float32) for key in packed.files}
        self.options = np.array(STEERING, dtype=np.float32)
        self.fact = {name: i for i, name in enumerate(FACTS)}
        self.previous = 0.0                                                  # the last steering option (-1 .. 1)

    def layer(self, x, name):
        return x @ self.w[name + ".weight"].T + self.w[name + ".bias"]

    def encode(self, lidar):
        return self.layer(relu(self.layer(lidar, "encoder.net.0")), "encoder.net.2")

    def predict(self, z, act, spd):
        x = np.concatenate([z, act, spd], axis=1)
        h = relu(self.layer(x, "predictor.net.0"))
        h = relu(self.layer(h, "predictor.net.2"))
        return self.layer(h, "predictor.net.4")

    def read(self, z):                                                       # the probe (zond): z -> FACTS
        return self.layer(relu(self.layer(z, "zond.0")), "zond.2")

    def score(self, facts):
        # the closest wall; a diagonal counts /1.4 (in a corridor it is ~1.4x farther), the front /2. bigger = safer
        f = self.fact
        walls = np.stack([facts[:, f["right"]], facts[:, f["left"]], facts[:, f["front_right"]] / 1.4,
                          facts[:, f["front_left"]] / 1.4, facts[:, f["front"]] / 2], axis=1)
        return walls.min(axis=1)

    def step(self, obs):
        scan = np.nan_to_num(np.asarray(obs["lidar"], dtype=np.float32), nan=MAX_RANGE, posinf=MAX_RANGE)
        lidar = np.minimum(scan[self.beams], MAX_RANGE) / MAX_RANGE         # like clean_lidar

        K = len(self.options)
        z = np.repeat(self.encode(lidar[None]), K, axis=0)                  # (9, 32): one start for every option
        act = np.stack([np.full(K, THROTTLE / THROTTLE_MAX, np.float32), self.options], axis=1)
        spd = np.full((K, 1), obs["speed"] / SPEED_MAX, np.float32)
        worst = np.full(K, np.inf, np.float32)                               # the closest wall on the WHOLE path
        for _ in range(STEPS):
            z = self.predict(z, act, spd)
            if GUARD:
                z = z / np.linalg.norm(z, axis=1, keepdims=True) * math.sqrt(LATENT)
            worst = np.minimum(worst, self.score(np.clip(self.read(z), 0, 1)))
        worst = worst - SMOOTH * np.abs(self.options - self.previous)
        self.previous = float(self.options[int(np.argmax(worst))])

        speed = SPEED
        mid = len(scan) // 2
        front = float(np.min(scan[mid - 4 : mid + 5]))
        if front < SAFE_FRONT:
            speed = min(speed, max(0.5, front * 2.0))
        steer = self.previous * AUTODRIVE_MAX_STEER
        return {"steer": max(-self.max_steer, min(self.max_steer, steer)), "speed": speed}
